//! The firewall rules, as an nftables script: for each restricted role's Unix users, port 443 and 80 connections
//! are redirected to the proxy, DNS to the resolver, and (once the role is enforced) everything else that leaves the
//! machine is refused. Other users are untouched. Applied by root (`fleetlayer-egress firewall --apply`).

use crate::settings::{Mode, Settings};

pub const TABLE: &str = "fleetlayer_egress";

fn users(list: &[String]) -> String {
    let quoted: Vec<String> = list.iter().map(|u| format!("\"{u}\"")).collect();
    format!("{{ {} }}", quoted.join(", "))
}

pub fn script(s: &Settings, source: &str) -> String {
    let p = &s.ports;
    let mut out = String::new();
    out.push_str(&format!(
        "#!/usr/sbin/nft -f\n# Fleetlayer egress firewall, generated by `fleetlayer-egress firewall` from {source}.\n\
         # Restricted roles reach the internet only through the egress proxy ({}) and resolver ({}).\n\
         # Regenerate it after changing roles or ports; host lists need no change here.\n\
         table inet {TABLE}\ndelete table inet {TABLE}\n",
        p.proxy, p.dns
    ));
    if s.roles.is_empty() {
        out.push_str("# No roles: nothing to restrict.\n");
        return out;
    }
    out.push_str(&format!("table inet {TABLE} {{\n"));
    out.push_str("  chain to_proxy {\n    type nat hook output priority -100; policy accept;\n");
    for r in &s.roles {
        let u = users(&r.users);
        out.push_str(&format!("    # role {}\n", r.name));
        out.push_str(&format!("    meta skuid {u} tcp dport 443 redirect to :{}\n", p.tls));
        out.push_str(&format!("    meta skuid {u} tcp dport 80 redirect to :{}\n", p.http));
        out.push_str(&format!("    meta skuid {u} meta l4proto {{ tcp, udp }} th dport 53 redirect to :{}\n", p.dns));
    }
    out.push_str("  }\n");
    out.push_str("  chain outbound {\n    type filter hook output priority 0; policy accept;\n");
    for r in &s.roles {
        let u = users(&r.users);
        out.push_str(&format!("    # role {} ({})\n", r.name, r.mode.word()));
        out.push_str(&format!(
            "    meta skuid {u} fib daddr type local tcp dport {{ {}, {}, {}, {} }} accept\n",
            p.proxy, p.tls, p.http, p.dns
        ));
        out.push_str(&format!("    meta skuid {u} fib daddr type local udp dport {} accept\n", p.dns));
        if r.loopback {
            out.push_str(&format!("    meta skuid {u} fib daddr type local accept\n"));
        }
        match r.mode {
            Mode::Enforce => {
                out.push_str(&format!("    meta skuid {u} meta l4proto tcp reject with tcp reset\n"));
                out.push_str(&format!("    meta skuid {u} reject\n"));
            }
            Mode::Log => {
                // Everything else goes through, and new connections show in the kernel log (`journalctl -k`).
                out.push_str(&format!(
                    "    meta skuid {u} ct state new limit rate 20/minute log prefix \"fleetlayer-egress {}: \" level info\n",
                    r.name
                ));
            }
        }
    }
    out.push_str("  }\n}\n");
    out
}

/// A systemd unit that applies the rules at boot, before the network is up.
pub fn unit(binary: &str, settings: &str) -> String {
    format!(
        "# /etc/systemd/system/fleetlayer-egress-firewall.service\n[Unit]\nDescription=Fleetlayer egress firewall \
         (restricted roles reach only the egress proxy)\nBefore=network-pre.target\nWants=network-pre.target\n\n\
         [Service]\nType=oneshot\nRemainAfterExit=yes\nExecStart={binary} firewall --apply --settings {settings}\n\
         ExecStop={binary} firewall --remove\n\n[Install]\nWantedBy=multi-user.target\n"
    )
}
